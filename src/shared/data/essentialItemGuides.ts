/** 전자 입국신고 가이드 키 — 배너·체크리스트 아이템 판정에 공용으로 쓴다 */
export const ENTRY_DECLARATION_GUIDE_KEY = "entry-declaration";

/** 이름 매칭용 정규화: 소문자 + 공백 제거 */
const normalize = (value: string) => value.toLowerCase().replace(/\s+/g, "");

/**
 * (정규화 키워드, 가이드) 쌍을 길이 내림차순으로 펼쳐 둔다.
 * 짧은 키워드가 긴 키워드를 선점하는 것을 막기 위함 — "비자카드"는
 * "비자"(비자 가이드)가 아니라 "비자카드"(결제카드 가이드)에 매칭돼야 한다.
 */
const KEYWORD_INDEX = ESSENTIAL_ITEM_GUIDES.flatMap((guide) =>
  guide.matchKeywords.map((keyword) => ({
    keyword: normalize(keyword),
    guide,
  })),
).sort((a, b) => b.keyword.length - a.keyword.length);

/** 아이템 이름으로 필수 준비물 가이드를 찾는다(최장 키워드 우선). 없으면 null. */
export function findEssentialGuide(
  itemName: string,
): EssentialItemGuide | null {
  const normalized = normalize(itemName);
  if (!normalized) return null;

  return (
    KEYWORD_INDEX.find(({ keyword }) => normalized.includes(keyword))?.guide ??
    null
  );
}
